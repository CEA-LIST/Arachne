type GenReplica = Replica<Si05boardLog, Tcsb<Si05board>>;

struct BoardGen {
    replicas: [GenReplica; 3],
}

impl GenSide for BoardGen {
    type Msg = EventMessage<Si05board>;

    fn fresh() -> Self {
        let (a, b, c) = triplet_log::<Si05boardLog>();
        BoardGen {
            replicas: [a, b, c],
        }
    }

    fn opener() -> Value {
        json!({"Board": "New"})
    }

    fn send(&mut self, at: usize, op: Value) -> Result<Self::Msg, String> {
        let op: Si05board = serde_json::from_value(op.clone()).unwrap_or_else(|error| {
            panic!("the typed encoder built no `Si05board`: {error}\n{op}")
        });
        self.replicas[at]
            .send(op)
            .map_err(|rejection| rejection.to_string())
    }

    fn receive(&mut self, at: usize, message: Self::Msg) {
        self.replicas[at].receive(message);
    }

    fn tag(message: &Self::Msg) -> String {
        let event = message.event();
        format!(
            "{}@{} L{}",
            event.id().origin_id(),
            event.id().seq(),
            event.lamport().val()
        )
    }

    fn value(&self, at: usize) -> Value {
        let value: Si05boardValue = self.replicas[at].query(&Read::<Si05boardValue>::new());
        serde_json::to_value(&value.board).expect("the board value serializes")
    }

    fn graph(&self, at: usize) -> (Vec<Value>, Vec<(usize, usize, String)>) {
        let value: Si05boardValue = self.replicas[at].query(&Read::<Si05boardValue>::new());
        let graph = &value.refs;
        let vertices = graph
            .node_indices()
            .map(|i| serde_json::to_value(&graph[i]).expect("a vertex serializes"))
            .collect();
        let arcs = graph
            .edge_indices()
            .map(|e| {
                let (from, to) = graph.edge_endpoints(e).expect("an edge has endpoints");
                let kind = serde_json::to_value(&graph[e]).expect("an edge kind serializes");
                let kind = kind
                    .as_object()
                    .and_then(|map| map.keys().next().cloned())
                    .or_else(|| kind.as_str().map(str::to_string))
                    .unwrap_or_else(|| kind.to_string());
                (from.index(), to.index(), kind)
            })
            .collect();
        (vertices, arcs)
    }

    fn feature_of(edge: &str) -> &'static str {
        match edge {
            // The arc kinds of `references.rs`: `CardToCard` is `blocker`
            // (`CardBlockerEdge`), `CardToCard2` is `related`.
            "CardToCard" => "blocker",
            "CardToCard2" => "related",
            other => panic!("an edge kind this board does not have: {other}"),
        }
    }
}

