/// Where a card sits.
#[derive(Clone, Copy, Debug)]
enum At {
    Cards(usize),
    Pinned,
}

struct Slots {
    board: ClassSlot,
    card: ClassSlot,
    cards: FeatureSlot,
    pinned: FeatureSlot,
    title: FeatureSlot,
    blocker: FeatureSlot,
    related: FeatureSlot,
}

impl Slots {
    fn new() -> Slots {
        let sem = table(&descriptor());
        let board = class_slot(&sem, "Board");
        let card = class_slot(&sem, "Card");
        Slots {
            board,
            card,
            cards: feature_slot(&sem, board, "cards"),
            pinned: feature_slot(&sem, board, "pinned"),
            title: feature_slot(&sem, card, "title"),
            blocker: feature_slot(&sem, card, "blocker"),
            related: feature_slot(&sem, card, "related"),
        }
    }

    fn on_board(&self, inner: InstanceOp) -> ModelOp {
        ModelOp::Instance(InstanceOp::variant(self.board, inner))
    }

    fn on_card(&self, at: At, inner: InstanceOp) -> ModelOp {
        let card = InstanceOp::variant(self.card, inner);
        self.on_board(match at {
            At::Cards(i) => InstanceOp::field(self.cards, InstanceOp::at(i, card)),
            At::Pinned => InstanceOp::field(self.pinned, InstanceOp::set(card)),
        })
    }
}

fn gen_on_card(at: At, inner: Value) -> Value {
    match at {
        At::Cards(i) => json!({"Board": {"Cards": {"Update": {"pos": i, "op": inner}}}}),
        At::Pinned => json!({"Board": {"Pinned": {"Set": inner}}}),
    }
}

/// The label of the card at a place, for the source of a link.
fn label_at(at: At) -> &'static str {
    match at {
        At::Cards(0) => "x",
        At::Cards(1) => "y",
        At::Cards(2) => "z",
        At::Pinned => "P",
        At::Cards(other) => panic!("no card is labelled at Board.cards[{other}]"),
    }
}

impl Twin<BoardGen> {
    fn root(&mut self, s: &Slots) {
        self.broadcast(
            0,
            "the root",
            s.on_board(InstanceOp::New),
            json!({"Board": "New"}),
        );
    }

    /// A card created at `Board.cards[pos]` on replica 0, delivered, labelled.
    fn new_card(&mut self, s: &Slots, pos: usize, label: &str) {
        let before = self.vertex_set(0);
        self.broadcast(
            0,
            &format!("create {label}"),
            s.on_board(InstanceOp::field(
                s.cards,
                InstanceOp::insert(pos, InstanceOp::variant(s.card, InstanceOp::New)),
            )),
            json!({"Board": {"Cards": {"Insert": {"pos": pos, "op": "New"}}}}),
        );
        self.label_new_vertex(0, &before, label);
        let doc = self.identified(0);
        let id = doc["cards"][pos][ID]
            .as_str()
            .unwrap_or_else(|| panic!("no identity at Board.cards[{pos}] in {doc}"))
            .to_string();
        self.label_identity(&id, label);
    }

    /// A card put in `Board.pinned` on replica 0, delivered, its vertex
    /// labelled `P` by its place.
    fn put_pinned(&mut self, s: &Slots) {
        let before = self.vertex_set(0);
        self.broadcast(
            0,
            "put a card in Board.pinned",
            s.on_board(InstanceOp::field(
                s.pinned,
                InstanceOp::set(InstanceOp::variant(s.card, InstanceOp::New)),
            )),
            json!({"Board": {"Pinned": {"Set": "New"}}}),
        );
        self.label_new_vertex(0, &before, "P");
    }

    /// One character typed at `pos` into the title of the card at `at`.
    fn type_char(
        &mut self,
        s: &Slots,
        writer: usize,
        at: At,
        pos: usize,
        ch: char,
    ) -> Pair<EventMessage<Si05board>> {
        self.send(
            writer,
            &format!("type {ch:?} into the title of {at:?}"),
            s.on_card(
                at,
                InstanceOp::field(
                    s.title,
                    InstanceOp::set(InstanceOp::Leaf(LeafOp::InsertChar { pos, ch })),
                ),
            ),
            gen_on_card(
                at,
                json!({"Title": {"Set": {"Insert": {"content": ch, "pos": pos}}}}),
            ),
        )
    }

    /// `Unset` of `Board.pinned`.
    fn unset_pinned(&mut self, s: &Slots, writer: usize) -> Pair<EventMessage<Si05board>> {
        self.send(
            writer,
            "unset Board.pinned",
            s.on_board(InstanceOp::field(s.pinned, InstanceOp::unset())),
            json!({"Board": {"Pinned": "Unset"}}),
        )
    }

    /// `Delete` of `Board.cards[pos]`.
    fn delete_card(
        &mut self,
        s: &Slots,
        writer: usize,
        pos: usize,
    ) -> Pair<EventMessage<Si05board>> {
        self.send(
            writer,
            &format!("delete Board.cards[{pos}]"),
            s.on_board(InstanceOp::field(s.cards, InstanceOp::delete(pos))),
            json!({"Board": {"Cards": {"Delete": {"pos": pos}}}}),
        )
    }

    /// K2's `Link` from the card at `from` to the card labelled `target`, at
    /// `feature`.
    fn link(
        &mut self,
        s: &Slots,
        writer: usize,
        from: At,
        feature: &str,
        target: &str,
    ) -> Pair<EventMessage<Si05board>> {
        let source = label_at(from);
        let slot = if feature == "blocker" {
            s.blocker
        } else {
            s.related
        };
        let arc = if feature == "blocker" {
            "CardToCard"
        } else {
            "CardToCard2"
        };
        let id = self.identity(target);
        let generated = json!({"AddReference": {arc: {
            "source": self.vertex_path(source),
            "target": self.vertex_path(target),
            "kind": null
        }}});
        self.send(
            writer,
            &format!("link {source}.{feature} -> {target}"),
            s.on_card(
                from,
                InstanceOp::field(slot, InstanceOp::Leaf(LeafOp::Link(id))),
            ),
            generated,
        )
    }
}

/// The base: the root, `x`, `y`, `z` at `Board.cards[0..3]` titled `x`, `y`,
/// `z`, and a card in `Board.pinned` titled `p`, built on replica 0 and
/// delivered to all; the pinned card's served identity is labelled `P`.
fn base(s: &Slots) -> Twin<BoardGen> {
    let mut twin: Twin<BoardGen> = Twin::new(&descriptor());
    twin.root(s);
    for (pos, label) in ["x", "y", "z"].into_iter().enumerate() {
        twin.new_card(s, pos, label);
        let ch = label.chars().next().expect("a one-letter label");
        let pair = twin.type_char(s, 0, At::Cards(pos), 0, ch);
        twin.deliver(1, &pair);
        twin.deliver(2, &pair);
    }
    twin.put_pinned(s);
    let pair = twin.type_char(s, 0, At::Pinned, 0, 'p');
    twin.deliver(1, &pair);
    twin.deliver(2, &pair);
    let doc = twin.identified(0);
    let id = doc["pinned"][ID]
        .as_str()
        .unwrap_or_else(|| panic!("the titled pinned card carries no identity: {doc}"))
        .to_string();
    twin.label_identity(&id, "P");
    twin
}

/// The interpreted projection of replica `at`: the titles of `Board.cards`,
/// the pinned card (absent, or its title), and the links of every card.
fn project_interp(twin: &Twin<BoardGen>, at: usize) -> Result<Projection, String> {
    let doc = twin.identified(at);
    let mut links = BTreeSet::new();
    let mut titles = Vec::new();
    for card in doc["cards"].as_array().cloned().unwrap_or_default() {
        let id = card[ID]
            .as_str()
            .ok_or_else(|| format!("a card carries no identity: {card}"))?;
        let label = twin
            .identities
            .get(id)
            .cloned()
            .ok_or_else(|| format!("interpreted card {id} carries no label"))?;
        titles.push(json!(interp_text(card.get("title"))));
        twin.interp_links_of(&label, &card, &mut links)?;
    }
    let pinned = match doc.get("pinned") {
        None | Some(Value::Null) => Value::Null,
        Some(card) => {
            twin.interp_links_of("P", card, &mut links)?;
            json!({"title": interp_text(card.get("title"))})
        }
    };
    Ok(Projection {
        containment: json!({"cards": titles, "pinned": pinned}),
        links,
    })
}

/// The generated projection of replica `at`, read off the typed read and its
/// graph.
fn project_gen(twin: &Twin<BoardGen>, at: usize) -> Projection {
    let value = twin.gen_side.value(at);
    let titles: Vec<Value> = value["cards"]
        .as_array()
        .cloned()
        .unwrap_or_default()
        .iter()
        .map(|card| json!(gen_text(&card["title"])))
        .collect();
    let pinned = match &value["pinned"] {
        Value::Null => Value::Null,
        card => json!({"title": gen_text(&card["title"])}),
    };
    Projection {
        containment: json!({"cards": titles, "pinned": pinned}),
        links: twin
            .gen_links(at)
            .unwrap_or_else(|why| panic!("replica {at}, generated: {why}")),
    }
}

const PROJECT: Projector<'static, BoardGen> = Projector {
    interp: &project_interp,
    generated: &project_gen,
};

fn containment(cards: [&str; 3], pinned: &str) -> Value {
    json!({"cards": cards, "pinned": {"title": pinned}})
}

/// TT1a, the links to the pinned card the unset had seen: `a` links
/// `x.blocker -> P` and `y.related -> P`, delivered to all; then `b` unsets
/// `Board.pinned`, delivered. The `DeleteSubtree` had seen both arcs and
/// made them redundant; the text keeps the card on both paths; no link is
/// read.
#[test]
fn si08_target_twin_tt1a_links_to_the_pinned_card_the_unset_had_seen_stay_hidden() {
    let s = Slots::new();
    let mut twin = base(&s);
    for (from, feature) in [(At::Cards(0), "blocker"), (At::Cards(1), "related")] {
        let pair = twin.link(&s, 0, from, feature, "P");
        twin.deliver(1, &pair);
        twin.deliver(2, &pair);
    }
    let held = compare_sides(&twin, &PROJECT, "TT1a, before the unset", Sides::Both);
    assert_eq!(
        held.links,
        links(&[("x", "blocker", "P"), ("y", "related", "P")]),
        "TT1a premise: both paths read the two links before the unset"
    );
    let unset = twin.unset_pinned(&s, 1);
    twin.deliver(0, &unset);
    twin.deliver(2, &unset);
    let after = compare_sides(&twin, &PROJECT, "TT1a, after the unset", Sides::Both);
    assert_eq!(after.containment, containment(["x", "y", "z"], ""));
    assert_eq!(
        after.links,
        links(&[]),
        "TT1a: no link the unset had seen is read"
    );
}

/// TT1b, the same links, the unset concurrent with `c`'s title `q`: the
/// title adds the card's vertex again, but the arcs the unset had seen stay
/// redundant, so no link is read, in every order.
#[test]
fn si08_target_twin_tt1b_links_the_unset_had_seen_stay_hidden_when_a_concurrent_write_keeps_the_card()
 {
    let s = Slots::new();
    let schedule = || {
        let mut twin = base(&s);
        for (from, feature) in [(At::Cards(0), "blocker"), (At::Cards(1), "related")] {
            let pair = twin.link(&s, 0, from, feature, "P");
            twin.deliver(1, &pair);
            twin.deliver(2, &pair);
        }
        let unset = twin.unset_pinned(&s, 1);
        let title = twin.type_char(&s, 2, At::Pinned, 0, 'q');
        Run {
            twin,
            incoming: [
                vec![vec![unset.clone()], vec![title.clone()]],
                vec![vec![title]],
                vec![vec![unset]],
            ],
        }
    };
    let runs = every_order(
        "TT1b",
        Sides::Both,
        schedule,
        &PROJECT,
        |agreed| {
            assert_eq!(agreed.containment, containment(["x", "y", "z"], "q"));
            assert_eq!(
                agreed.links,
                links(&[]),
                "TT1b: no link the unset had seen is read, although c's title keeps the card"
            );
        },
        None,
        Sides::Both,
        |_, _| {},
    );
    assert_eq!(runs, 2, "a: 2 interleavings, b: 1 order, c: 1 order");
}

/// TT2, the gap (SI.07's OB1): `b` unsets `Board.pinned`; `c`, concurrently,
/// links `x.blocker -> P`, `x.related -> P` and `x.related -> z`. No write
/// the unset had not seen reaches the card, so the generated graph holds no
/// vertex for it and reads only `x.related -> z`, while the text keeps the
/// card served with title `""`. Under [`Sides::GeneratedOnly`] (the
/// rehearsal), `a` then types `r` into the card's title, delivered to all:
/// the generated graph adds the card's vertex again and reads the two arcs to
/// it again. That later write is the revival of ruling R1 (SI.07's OB2): the
/// interpreted card is served under a new identity and the links name the
/// old one, so the comparison of paths stops before it, and the rehearsal
/// prints what the interpreted path reads there without asserting it.
fn tt2(sides: Sides) {
    let s = Slots::new();
    let schedule = || {
        let mut twin = base(&s);
        let unset = twin.unset_pinned(&s, 1);
        let from_c = vec![
            twin.link(&s, 2, At::Cards(0), "blocker", "P"),
            twin.link(&s, 2, At::Cards(0), "related", "P"),
            twin.link(&s, 2, At::Cards(0), "related", "z"),
        ];
        Run {
            twin,
            incoming: [
                vec![vec![unset.clone()], from_c.clone()],
                vec![from_c],
                vec![vec![unset]],
            ],
        }
    };
    let revive = |twin: &mut Twin<BoardGen>| {
        let s = Slots::new();
        let pair = twin.type_char(&s, 0, At::Pinned, 0, 'r');
        twin.deliver(1, &pair);
        twin.deliver(2, &pair);
        "a types `r` into the pinned card's title (the revival of ruling R1)"
    };
    let after: Option<&dyn Fn(&mut Twin<BoardGen>) -> &'static str> = match sides {
        Sides::Both => None,
        Sides::GeneratedOnly => Some(&revive),
    };
    let runs = every_order(
        "TT2",
        sides,
        schedule,
        &PROJECT,
        |agreed| {
            assert_eq!(
                agreed.containment,
                containment(["x", "y", "z"], ""),
                "TT2: the text keeps the pinned card, its title emptied"
            );
            assert_eq!(
                agreed.links,
                links(&[("x", "related", "z")]),
                "TT2: no link to the pinned card is read while no write the unset had not seen reaches it"
            );
        },
        after,
        Sides::GeneratedOnly,
        |twin, agreed| {
            assert_eq!(
                agreed.containment,
                containment(["x", "y", "z"], "r"),
                "TT2 rehearsal, revived: the card holds `r`"
            );
            assert_eq!(
                agreed.links,
                links(&[
                    ("x", "blocker", "P"),
                    ("x", "related", "P"),
                    ("x", "related", "z")
                ]),
                "TT2 rehearsal, revived: the generated graph reads the arcs to the card's place again"
            );
            let interp: Vec<String> = (0..3)
                .map(|at| match project_interp(twin, at) {
                    Ok(projection) => format!("{:?}", projection.links),
                    Err(why) => format!("unlabelled: {why}"),
                })
                .collect();
            println!(
                "SI08 OB2 observation (not asserted): after the revival the generated runtime reads \
                 {:?}; the interpreted path reads, per replica, {interp:?}; the pinned card now serves \
                 {}",
                agreed.links,
                twin.identified(0)["pinned"][ID]
            );
        },
    );
    assert_eq!(runs, 4, "a: 4 interleavings, b: 1 order, c: 1 order");
}

