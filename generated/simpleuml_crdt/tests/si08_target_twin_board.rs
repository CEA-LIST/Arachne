//! SI.08, the target side of SI.07's P1, over an optional target:
//! `Board.pinned` of the board of `si05board.ecore`, a `Card` held by an
//! optional containment, and, for the rule's other side, a card of
//! `Board.cards`.
//!
//! The spec is `cea-cdrt-knowledge/spec/items/SI.08.md`. The claim: under the
//! identity rule, when a removal reaches an object whose creation it had seen
//! and the object stays served only because a text attribute keeps it (ST.04:
//! its title reads `""`), a link to that object written concurrently with the
//! removal is read exactly when the generated runtime reads the arc: not
//! while no write the removal had not seen has reached the object, and read
//! while, or once, such a write has reached it. The generated runtime is the
//! ground truth: its `DeleteSubtree` over the optional takes the card's
//! vertex away, a link adds no vertex, an arc is a candidate only between two
//! vertices the graph holds, and a write into the card adds its vertex again.
//!
//! The generated runtime is `fixtures/si05/si05board.ecore` of
//! `arachne-codegen/tests/`, generated by Arachne `2ef2a26` (`arachne generate
//! -p board_crdt`), the three source files SI.07 copied into
//! `fixtures/si07/board/`, compiled here as this test's own modules; its
//! `metamodel.json`, beside them, is the descriptor the interpreted path
//! runs, byte for byte Moirai's `si05board.metamodel.json`. The harness is
//! `si08_twin/mod.rs`.
//!
//! ```bash
//! cd generated/simpleuml_crdt && nice -n 10 cargo test -j 2 --test si08_target_twin_board
//! ```
