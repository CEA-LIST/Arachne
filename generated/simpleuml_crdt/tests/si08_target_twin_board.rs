/// TT4, the other side: `b` unsets `Board.pinned`; `c`, concurrently, links
/// `x.blocker -> P` and `x.related -> P`; `a`, concurrently, types `q` into
/// the card's title. `a`'s `AddVertex` is concurrent with the
/// `DeleteSubtree`, so the card keeps its vertex and both links are read on
/// both paths, in every order.
#[test]
fn si08_target_twin_tt4_a_write_the_unset_had_not_seen_keeps_the_links_to_the_pinned_card_read() {
    let s = Slots::new();
    let schedule = || {
        let mut twin = base(&s);
        let title = twin.type_char(&s, 0, At::Pinned, 0, 'q');
        let unset = twin.unset_pinned(&s, 1);
        let from_c = vec![
            twin.link(&s, 2, At::Cards(0), "blocker", "P"),
            twin.link(&s, 2, At::Cards(0), "related", "P"),
        ];
        Run {
            twin,
            incoming: [
                vec![vec![unset.clone()], from_c.clone()],
                vec![vec![title.clone()], from_c],
                vec![vec![title], vec![unset]],
            ],
        }
    };
    let runs = every_order(
        "TT4",
        Sides::Both,
        schedule,
        &PROJECT,
        |agreed| {
            assert_eq!(agreed.containment, containment(["x", "y", "z"], "q"));
            assert_eq!(
                agreed.links,
                links(&[("x", "blocker", "P"), ("x", "related", "P")]),
                "TT4: both links to the pinned card are read, a write the unset had not seen keeping it"
            );
        },
        None,
        Sides::Both,
        |_, _| {},
    );
    assert_eq!(
        runs, 18,
        "a: 3 interleavings, b: 3 interleavings, c: 2 interleavings"
    );
}

/// TT8, a sequence-held target kept by a concurrent write: `b` deletes `y`
/// from `Board.cards`; `c`, concurrently, links `x.blocker -> y` and
/// `x.related -> y`; `a`, concurrently, types `q` into `y`'s title. `a`'s
/// update keeps `y` in the sequence and its vertex in the graph, so both
/// links are read on both paths, in every order.
#[test]
fn si08_target_twin_tt8_a_sequence_held_target_kept_by_a_concurrent_write_keeps_its_links_read() {
    let s = Slots::new();
    let schedule = || {
        let mut twin = base(&s);
        let title = twin.type_char(&s, 0, At::Cards(1), 0, 'q');
        let delete = twin.delete_card(&s, 1, 1);
        let from_c = vec![
            twin.link(&s, 2, At::Cards(0), "blocker", "y"),
            twin.link(&s, 2, At::Cards(0), "related", "y"),
        ];
        Run {
            twin,
            incoming: [
                vec![vec![delete.clone()], from_c.clone()],
                vec![vec![title.clone()], from_c],
                vec![vec![title], vec![delete]],
            ],
        }
    };
    let runs = every_order(
        "TT8",
        Sides::Both,
        schedule,
        &PROJECT,
        |agreed| {
            assert_eq!(
                agreed.containment,
                containment(["x", "q", "z"], "p"),
                "TT8: the sequence keeps y, holding `q`"
            );
            assert_eq!(
                agreed.links,
                links(&[("x", "blocker", "y"), ("x", "related", "y")]),
                "TT8: both links to y are read, a write the deletion had not seen keeping it"
            );
        },
        None,
        Sides::Both,
        |_, _| {},
    );
    assert_eq!(
        runs, 18,
        "a: 3 interleavings, b: 3 interleavings, c: 2 interleavings"
    );
}
