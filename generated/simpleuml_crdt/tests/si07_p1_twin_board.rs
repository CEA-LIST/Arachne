/// TB3, the other side: `b` unsets `Board.pinned`; `c`, concurrently, links
/// the pinned card's `blocker` to `y` and `related` to `z` and then types `q`
/// into its title. The title is a write the unset had not seen, so the card
/// keeps its vertex and both links are read on both paths, in every order.
#[test]
fn si07_p1_twin_tb3_a_write_concurrent_with_the_unset_keeps_the_links_read() {
    let s = Slots::new();
    let schedule = || {
        let mut twin = base(&s);
        let unset = twin.unset_pinned(&s, 1);
        let blocker = twin.link(&s, 2, At::Pinned, "P", "blocker", "y");
        let related = twin.link(&s, 2, At::Pinned, "P", "related", "z");
        let title = twin.type_char(&s, 2, At::Pinned, 0, 'q');
        Run {
            twin,
            incoming: [
                vec![
                    vec![unset.clone()],
                    vec![blocker.clone(), related.clone(), title.clone()],
                ],
                vec![vec![blocker, related, title]],
                vec![vec![unset]],
            ],
        }
    };
    let runs = every_order(
        "TB3",
        Sides::Both,
        schedule,
        project,
        |agreed| {
            assert_eq!(
                agreed.containment,
                json!({"cards": base_titles(), "pinned": {"title": "q"}}),
                "TB3: the card keeps `q`, typed concurrently with the unset"
            );
            assert_eq!(
                agreed.links,
                links(&[("P", "blocker", "y"), ("P", "related", "z")]),
                "TB3: the links are read, the card being kept by a write the unset had not seen"
            );
        },
        None,
        |_| {},
    );
    assert_eq!(runs, 4, "a: 4 interleavings, b: 1 order, c: 1 order");
}
