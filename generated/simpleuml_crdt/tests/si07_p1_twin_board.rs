/// Where a card sits.
#[derive(Clone, Copy, Debug)]
enum At {
    Cards(usize),
    Pinned,
}

struct Slots {
    board: ClassSlot,
    card: ClassSlot,
    cards: FeatureSlot,
    pinned: FeatureSlot,
    title: FeatureSlot,
    blocker: FeatureSlot,
    related: FeatureSlot,
}

impl Slots {
    fn new() -> Slots {
        let sem = table(&descriptor());
        let board = class_slot(&sem, "Board");
        let card = class_slot(&sem, "Card");
        Slots {
            board,
            card,
            cards: feature_slot(&sem, board, "cards"),
            pinned: feature_slot(&sem, board, "pinned"),
            title: feature_slot(&sem, card, "title"),
            blocker: feature_slot(&sem, card, "blocker"),
            related: feature_slot(&sem, card, "related"),
        }
    }

    fn on_board(&self, inner: InstanceOp) -> ModelOp {
        ModelOp::Instance(InstanceOp::variant(self.board, inner))
    }

    fn on_card(&self, at: At, inner: InstanceOp) -> ModelOp {
        let card = InstanceOp::variant(self.card, inner);
        self.on_board(match at {
            At::Cards(i) => InstanceOp::field(self.cards, InstanceOp::at(i, card)),
            At::Pinned => InstanceOp::field(self.pinned, InstanceOp::set(card)),
        })
    }
}

fn gen_on_card(at: At, inner: Value) -> Value {
    match at {
        At::Cards(i) => json!({"Board": {"Cards": {"Update": {"pos": i, "op": inner}}}}),
        At::Pinned => json!({"Board": {"Pinned": {"Set": inner}}}),
    }
}

impl Twin<BoardGen> {
    fn root(&mut self, s: &Slots) {
        self.broadcast(
            0,
            "the root",
            s.on_board(InstanceOp::New),
            json!({"Board": "New"}),
        );
    }

    /// A card created at `Board.cards[pos]` on replica 0, delivered, labelled.
    fn new_card(&mut self, s: &Slots, pos: usize, label: &str) {
        let before = self.vertex_set(0);
        self.broadcast(
            0,
            &format!("create {label}"),
            s.on_board(InstanceOp::field(
                s.cards,
                InstanceOp::insert(pos, InstanceOp::variant(s.card, InstanceOp::New)),
            )),
            json!({"Board": {"Cards": {"Insert": {"pos": pos, "op": "New"}}}}),
        );
        self.label_new_vertex(0, &before, label);
        let doc = self.identified(0);
        let id = doc["cards"][pos][ID]
            .as_str()
            .unwrap_or_else(|| panic!("no identity at Board.cards[{pos}] in {doc}"))
            .to_string();
        self.identities.insert(id, label.to_string());
    }

    /// A card put in `Board.pinned` on replica 0, delivered, labelled `P` by
    /// its place.
    fn put_pinned(&mut self, s: &Slots) {
        let before = self.vertex_set(0);
        self.broadcast(
            0,
            "put a card in Board.pinned",
            s.on_board(InstanceOp::field(
                s.pinned,
                InstanceOp::set(InstanceOp::variant(s.card, InstanceOp::New)),
            )),
            json!({"Board": {"Pinned": {"Set": "New"}}}),
        );
        self.label_new_vertex(0, &before, "P");
    }

    /// One character typed at `pos` into the title of the card at `at`.
    fn type_char(
        &mut self,
        s: &Slots,
        writer: usize,
        at: At,
        pos: usize,
        ch: char,
    ) -> Pair<EventMessage<Si05board>> {
        self.send(
            writer,
            &format!("type {ch:?} into the title of {at:?}"),
            s.on_card(
                at,
                InstanceOp::field(
                    s.title,
                    InstanceOp::set(InstanceOp::Leaf(LeafOp::InsertChar { pos, ch })),
                ),
            ),
            gen_on_card(
                at,
                json!({"Title": {"Set": {"Insert": {"content": ch, "pos": pos}}}}),
            ),
        )
    }

    /// `Unset` of `Board.pinned`.
    fn unset_pinned(&mut self, s: &Slots, writer: usize) -> Pair<EventMessage<Si05board>> {
        self.send(
            writer,
            "unset Board.pinned",
            s.on_board(InstanceOp::field(s.pinned, InstanceOp::unset())),
            json!({"Board": {"Pinned": "Unset"}}),
        )
    }

    /// K2's `Link` from the card labelled `source` at `at` to the card
    /// labelled `target`, at `feature`.
    fn link(
        &mut self,
        s: &Slots,
        writer: usize,
        at: At,
        source: &str,
        feature: &str,
        target: &str,
    ) -> Pair<EventMessage<Si05board>> {
        let slot = if feature == "blocker" {
            s.blocker
        } else {
            s.related
        };
        let arc = if feature == "blocker" {
            "CardToCard"
        } else {
            "CardToCard2"
        };
        let id = self.identity(target);
        let generated = json!({"AddReference": {arc: {
            "source": self.vertex_path(source),
            "target": self.vertex_path(target),
            "kind": null
        }}});
        self.send(
            writer,
            &format!("link {source}.{feature} -> {target}"),
            s.on_card(
                at,
                InstanceOp::field(slot, InstanceOp::Leaf(LeafOp::Link(id))),
            ),
            generated,
        )
    }
}

/// The base: the root, `x`, `y`, `z` at `Board.cards[0..3]` titled `x`, `y`,
/// `z`, and a card in `Board.pinned` titled `p`, built on replica 0 and
/// delivered to all.
fn base(s: &Slots) -> Twin<BoardGen> {
    let mut twin: Twin<BoardGen> = Twin::new(&descriptor());
    twin.root(s);
    for (pos, label) in ["x", "y", "z"].into_iter().enumerate() {
        twin.new_card(s, pos, label);
        let ch = label.chars().next().expect("a one-letter label");
        let pair = twin.type_char(s, 0, At::Cards(pos), 0, ch);
        twin.deliver(1, &pair);
        twin.deliver(2, &pair);
    }
    twin.put_pinned(s);
    let pair = twin.type_char(s, 0, At::Pinned, 0, 'p');
    twin.deliver(1, &pair);
    twin.deliver(2, &pair);
    twin
}

/// Both paths' projection of replica `at`: the titles of `Board.cards`, the
/// pinned card (absent, or its title), and the links of every card.
fn project(twin: &Twin<BoardGen>, at: usize) -> (Projection, Projection) {
    // The interpreted side, off the identified read.
    let doc = twin.identified(at);
    let mut links = BTreeSet::new();
    let cards = doc["cards"].as_array().cloned().unwrap_or_default();
    let mut titles = Vec::new();
    for card in &cards {
        let id = card[ID].as_str().expect("a card carries its identity");
        let label = twin
            .identities
            .get(id)
            .cloned()
            .unwrap_or_else(|| panic!("interpreted card {id} carries no label"));
        titles.push(json!(interp_text(card.get("title"))));
        twin.interp_links_of(&label, card, &mut links)
            .unwrap_or_else(|why| panic!("replica {at}, interpreted: {why}"));
    }
    let pinned = match doc.get("pinned") {
        None | Some(Value::Null) => Value::Null,
        Some(card) => {
            twin.interp_links_of("P", card, &mut links)
                .unwrap_or_else(|why| panic!("replica {at}, interpreted: {why}"));
            json!({"title": interp_text(card.get("title"))})
        }
    };
    let interp = Projection {
        containment: json!({"cards": titles, "pinned": pinned}),
        links,
    };

    // The generated side, off the typed read and its graph.
    let value = twin.gen_side.value(at);
    let titles: Vec<Value> = value["cards"]
        .as_array()
        .cloned()
        .unwrap_or_default()
        .iter()
        .map(|card| json!(gen_text(&card["title"])))
        .collect();
    let pinned = match &value["pinned"] {
        Value::Null => Value::Null,
        card => json!({"title": gen_text(&card["title"])}),
    };
    let generated = Projection {
        containment: json!({"cards": titles, "pinned": pinned}),
        links: twin
            .gen_links(at)
            .unwrap_or_else(|why| panic!("replica {at}, generated: {why}")),
    };
    (interp, generated)
}

fn links(items: &[(&str, &str, &str)]) -> BTreeSet<(String, String, String)> {
    items
        .iter()
        .map(|(s, f, t)| (s.to_string(), f.to_string(), t.to_string()))
        .collect()
}

fn base_titles() -> Value {
    json!(["x", "y", "z"])
}

/// TB1, the links the removal had seen. The pinned card links `blocker -> y`
/// and `related -> y, z`, delivered to all; then `b` unsets `Board.pinned`,
/// delivered to all. The text keeps the card (title `""`) on both paths; the
/// removal saw the links, so neither path reads them.
#[test]
fn si07_p1_twin_tb1_links_the_unset_had_seen_are_not_read_from_the_card_a_text_keeps() {
    let s = Slots::new();
    let mut twin = base(&s);
    for (feature, target) in [("blocker", "y"), ("related", "y"), ("related", "z")] {
        let pair = twin.link(&s, 0, At::Pinned, "P", feature, target);
        twin.deliver(1, &pair);
        twin.deliver(2, &pair);
    }
    let held = compare(&twin, &project, "TB1, before the unset");
    assert_eq!(
        held.links,
        links(&[
            ("P", "blocker", "y"),
            ("P", "related", "y"),
            ("P", "related", "z")
        ]),
        "TB1 premise: both paths read the three links before the unset"
    );
    let unset = twin.unset_pinned(&s, 1);
    twin.deliver(0, &unset);
    twin.deliver(2, &unset);
    let after = compare(&twin, &project, "TB1, after the unset");
    assert_eq!(
        after.containment,
        json!({"cards": base_titles(), "pinned": {"title": ""}}),
        "TB1: the text keeps the pinned card, its title emptied (ST.04)"
    );
    assert_eq!(
        after.links,
        links(&[]),
        "TB1: no link the unset had seen is read"
    );
}

/// TB2, the gap of SI.05's ruling R3.2. `b` unsets `Board.pinned`; `c`,
/// concurrently, links the pinned card's `blocker` to `y` and its `related`
/// to `z`. No write concurrent with the unset reaches the card, so the
/// generated graph holds no vertex for it once the unset is delivered, and
/// neither link is read, while the text keeps the card served with title
/// `""`. Then `a` types `r` into the card's title, delivered to all: that
/// write adds the card's vertex again, and the two links, which no removal
/// had seen, are read again.
fn tb2(sides: Sides) {
    let s = Slots::new();
    let schedule = || {
        let mut twin = base(&s);
        let unset = twin.unset_pinned(&s, 1);
        let blocker = twin.link(&s, 2, At::Pinned, "P", "blocker", "y");
        let related = twin.link(&s, 2, At::Pinned, "P", "related", "z");
        Run {
            twin,
            incoming: [
                vec![vec![unset.clone()], vec![blocker.clone(), related.clone()]],
                vec![vec![blocker, related]],
                vec![vec![unset]],
            ],
        }
    };
    let revive = |twin: &mut Twin<BoardGen>| {
        let s = Slots::new();
        let pair = twin.type_char(&s, 0, At::Pinned, 0, 'r');
        twin.deliver(1, &pair);
        twin.deliver(2, &pair);
        "a types `r` into the pinned card's title"
    };
    let runs = every_order(
        "TB2",
        sides,
        schedule,
        project,
        |agreed| {
            assert_eq!(
                agreed.containment,
                json!({"cards": base_titles(), "pinned": {"title": ""}}),
                "TB2: the text keeps the pinned card, its title emptied"
            );
            assert_eq!(
                agreed.links,
                links(&[]),
                "TB2: no link from the card is read while no write keeps it"
            );
        },
        Some(&revive),
        |agreed| {
            assert_eq!(
                agreed.containment,
                json!({"cards": base_titles(), "pinned": {"title": "r"}}),
                "TB2, revived: the card holds `r`"
            );
            assert_eq!(
                agreed.links,
                links(&[("P", "blocker", "y"), ("P", "related", "z")]),
                "TB2, revived: the links no removal had seen are read again"
            );
        },
    );
    assert_eq!(runs, 3, "a: 3 interleavings, b: 1 order, c: 1 order");
}

#[test]
fn si07_p1_twin_tb2_links_concurrent_with_the_unset_follow_the_cards_vertex() {
    tb2(Sides::Both);
}

