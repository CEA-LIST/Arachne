//! SI.07, claim P1 (parity), over an optional source: `Board.pinned` of the
//! board of `si05board.ecore`, a `Card` held by an optional containment.
//!
//! The spec is `cea-cdrt-knowledge/spec/items/SI.07.md`. The claim: under the
//! identity rule, when a removal reaches an object whose creation it had seen,
//! the links from that object that the removal had seen are no longer read,
//! even when the object stays served because a text attribute keeps it (ST.04:
//! its title reads `""`); a link from it concurrent with the removal is read
//! exactly when the generated runtime reads it. The generated runtime is the
//! ground truth: its `DeleteSubtree` over the optional takes the card's vertex
//! away, a link adds no vertex, and an arc is read only between two vertices
//! the graph holds; a later write into the card adds its vertex again.
//!
//! The generated runtime is `fixtures/si05/si05board.ecore` of
//! `arachne-codegen/tests/`, generated by Arachne `2ef2a26` (`arachne generate
//! -p board_crdt`), its three source files copied unchanged into
//! `fixtures/si07/board/` and compiled here as this test's own modules; its
//! `metamodel.json`, copied beside them, is the descriptor the interpreted
//! path runs, byte for byte Moirai's `si05board.metamodel.json` (sha256
//! `1256bc54...`). The harness is `si07_twin/mod.rs`.
//!
//! ```bash
//! cd generated/simpleuml_crdt && nice -n 10 cargo test -j 2 --test si07_p1_twin_board
//! ```
