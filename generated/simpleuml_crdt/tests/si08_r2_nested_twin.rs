//! SI.08 round 2, the twin: links to and from a card a removal reached from
//! above, held path against path. The board is Moirai's
//! `moirai-interp/tests/fixtures/si08/si08nest.ecore`: a `Frame` in an
//! optional (`Board.pinned`) or at a key (`Board.frames["f"]`), holding a
//! `Card` at a single containment of a class with no subclass
//! (`Frame.head`, a `record!` field on the generated side), in an optional
//! (`Frame.extra`) and at a key (`Frame.slots["k"]`). The removal is an
//! `Unset` of `Board.pinned`, a `Remove` of `"f"` or a `Clear` of
//! `Board.frames`, each a `DeleteSubtree` over the frame's place or the map on
//! the generated side.
//!
//! The spec is `cea-cdrt-knowledge/spec/items/SI.08.md`, section "Round 2,
//! written before any rerun". The generated runtime is the ground truth: a
//! write adds the vertex of every record its path passes through (and of no
//! record it does not), a link adds no vertex, a `DeleteSubtree` takes away
//! the vertex additions and the arcs it had seen below its prefix, and an arc
//! is a candidate only between two vertices the graph holds; a single-valued
//! reference keeps the greatest candidate by `FairPolicy`. The interpreted
//! path must read the same links.
//!
//! The generated runtime is `si08nest.ecore` generated by Arachne `667db42`
//! (`arachne generate -p nest_crdt`), its three source files copied into
//! `fixtures/si08/nest/` and compiled here as this test's own modules; its
//! `metamodel.json` there is byte for byte Moirai's
//! `si08nest.metamodel.json`. The harness is round 1's `si08_twin/mod.rs`,
//! read and not changed: a card is labelled by the one vertex its first write
//! added and by the identity it is served under, which no schedule here
//! moves.
//!
