/// Where the frame sits.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum Holder {
    Pinned,
    Keyed,
}

/// The removal that reaches the frame, and with it every card inside it.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum Removal {
    Unset,
    Remove,
    Clear,
}

impl Removal {
    const ALL: [Removal; 3] = [Removal::Unset, Removal::Remove, Removal::Clear];

    fn holder(self) -> Holder {
        match self {
            Removal::Unset => Holder::Pinned,
            Removal::Remove | Removal::Clear => Holder::Keyed,
        }
    }

    fn name(self) -> &'static str {
        match self {
            Removal::Unset => "Unset of Board.pinned",
            Removal::Remove => "Remove of Board.frames[f]",
            Removal::Clear => "Clear of Board.frames",
        }
    }
}

/// Where the card a schedule targets sits inside the frame.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum Place {
    Head,
    Extra,
    Slot,
}

impl Place {
    const ALL: [Place; 3] = [Place::Head, Place::Extra, Place::Slot];

    fn label(self) -> &'static str {
        match self {
            Place::Head => "H",
            Place::Extra => "E",
            Place::Slot => "S",
        }
    }

    fn letter(self) -> char {
        match self {
            Place::Head => 'h',
            Place::Extra => 'e',
            Place::Slot => 's',
        }
    }
}

/// Where a card sits.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum At {
    Cards(usize),
    Frame(Holder, Place),
}

/// The label of the card at a place, for the source of a link.
fn label_at(at: At) -> &'static str {
    match at {
        At::Cards(0) => "x",
        At::Cards(1) => "y",
        At::Cards(2) => "z",
        At::Frame(_, place) => place.label(),
        At::Cards(other) => panic!("no card is labelled at Board.cards[{other}]"),
    }
}

struct Slots {
    board: ClassSlot,
    frame: ClassSlot,
    card: ClassSlot,
    cards: FeatureSlot,
    pinned: FeatureSlot,
    frames: FeatureSlot,
    label: FeatureSlot,
    head: FeatureSlot,
    extra: FeatureSlot,
    slots: FeatureSlot,
    title: FeatureSlot,
    blocker: FeatureSlot,
    related: FeatureSlot,
}

impl Slots {
    fn new() -> Slots {
        let sem = table(&descriptor());
        let board = class_slot(&sem, "Board");
        let frame = class_slot(&sem, "Frame");
        let card = class_slot(&sem, "Card");
        Slots {
            board,
            frame,
            card,
            cards: feature_slot(&sem, board, "cards"),
            pinned: feature_slot(&sem, board, "pinned"),
            frames: feature_slot(&sem, board, "frames"),
            label: feature_slot(&sem, frame, "label"),
            head: feature_slot(&sem, frame, "head"),
            extra: feature_slot(&sem, frame, "extra"),
            slots: feature_slot(&sem, frame, "slots"),
            title: feature_slot(&sem, card, "title"),
            blocker: feature_slot(&sem, card, "blocker"),
            related: feature_slot(&sem, card, "related"),
        }
    }

    fn on_board(&self, inner: InstanceOp) -> ModelOp {
        ModelOp::Instance(InstanceOp::variant(self.board, inner))
    }

    fn on_frame(&self, holder: Holder, inner: InstanceOp) -> ModelOp {
        let frame = InstanceOp::variant(self.frame, inner);
        self.on_board(match holder {
            Holder::Pinned => InstanceOp::field(self.pinned, InstanceOp::set(frame)),
            Holder::Keyed => {
                InstanceOp::field(self.frames, InstanceOp::entry(Scalar::text("f"), frame))
            }
        })
    }

    fn on_card(&self, at: At, inner: InstanceOp) -> ModelOp {
        let card = InstanceOp::variant(self.card, inner);
        match at {
            At::Cards(i) => self.on_board(InstanceOp::field(self.cards, InstanceOp::at(i, card))),
            At::Frame(holder, place) => self.on_frame(
                holder,
                match place {
                    Place::Head => InstanceOp::field(self.head, card),
                    Place::Extra => InstanceOp::field(self.extra, InstanceOp::set(card)),
                    Place::Slot => {
                        InstanceOp::field(self.slots, InstanceOp::entry(Scalar::text("k"), card))
                    }
                },
            ),
        }
    }
}

fn gen_on_frame(holder: Holder, inner: Value) -> Value {
    match holder {
        Holder::Pinned => json!({"Board": {"Pinned": {"Set": inner}}}),
        Holder::Keyed => json!({"Board": {"Frames": {"Update": ["f", inner]}}}),
    }
}

fn gen_on_card(at: At, inner: Value) -> Value {
    match at {
        At::Cards(i) => json!({"Board": {"Cards": {"Update": {"pos": i, "op": inner}}}}),
        At::Frame(holder, Place::Head) => gen_on_frame(holder, json!({"Head": inner})),
        At::Frame(holder, Place::Extra) => gen_on_frame(holder, json!({"Extra": {"Set": inner}})),
        At::Frame(holder, Place::Slot) => {
            gen_on_frame(holder, json!({"Slots": {"Update": ["k", inner]}}))
        }
    }
}

type Sent = Pair<EventMessage<Si08nest>>;

impl Twin<NestGen> {
    fn root(&mut self, s: &Slots) {
        self.broadcast(
            0,
            "the root",
            s.on_board(InstanceOp::New),
            json!({"Board": "New"}),
        );
    }

    /// A card created at `Board.cards[pos]` on replica 0, delivered, labelled.
    fn new_card(&mut self, s: &Slots, pos: usize, label: &str) {
        let before = self.vertex_set(0);
        self.broadcast(
            0,
            &format!("create {label}"),
            s.on_board(InstanceOp::field(
                s.cards,
                InstanceOp::insert(pos, InstanceOp::variant(s.card, InstanceOp::New)),
            )),
            json!({"Board": {"Cards": {"Insert": {"pos": pos, "op": "New"}}}}),
        );
        self.label_new_vertex(0, &before, label);
        let doc = self.identified(0);
        let id = doc["cards"][pos][ID]
            .as_str()
            .unwrap_or_else(|| panic!("no identity at Board.cards[{pos}] in {doc}"))
            .to_string();
        self.label_identity(&id, label);
    }

    /// One character typed at `pos` into the title of the card at `at`.
    fn type_char(&mut self, s: &Slots, writer: usize, at: At, pos: usize, ch: char) -> Sent {
        self.send(
            writer,
            &format!("type {ch:?} into the title of {at:?}"),
            s.on_card(
                at,
                InstanceOp::field(
                    s.title,
                    InstanceOp::set(InstanceOp::Leaf(LeafOp::InsertChar { pos, ch })),
                ),
            ),
            gen_on_card(
                at,
                json!({"Title": {"Set": {"Insert": {"content": ch, "pos": pos}}}}),
            ),
        )
    }

    /// One character typed at `pos` into the label of the frame at `holder`.
    fn type_label(
        &mut self,
        s: &Slots,
        writer: usize,
        holder: Holder,
        pos: usize,
        ch: char,
    ) -> Sent {
        self.send(
            writer,
            &format!("type {ch:?} into the label of the frame at {holder:?}"),
            s.on_frame(
                holder,
                InstanceOp::field(
                    s.label,
                    InstanceOp::set(InstanceOp::Leaf(LeafOp::InsertChar { pos, ch })),
                ),
            ),
            gen_on_frame(
                holder,
                json!({"Label": {"Set": {"Insert": {"content": ch, "pos": pos}}}}),
            ),
        )
    }

    fn removal(&mut self, s: &Slots, writer: usize, removal: Removal) -> Sent {
        let (interp, generated) = match removal {
            Removal::Unset => (
                s.on_board(InstanceOp::field(s.pinned, InstanceOp::unset())),
                json!({"Board": {"Pinned": "Unset"}}),
            ),
            Removal::Remove => (
                s.on_board(InstanceOp::field(
                    s.frames,
                    InstanceOp::remove(Scalar::text("f")),
                )),
                json!({"Board": {"Frames": {"Remove": "f"}}}),
            ),
            Removal::Clear => (
                s.on_board(InstanceOp::field(s.frames, InstanceOp::clear())),
                json!({"Board": {"Frames": "Clear"}}),
            ),
        };
        self.send(writer, removal.name(), interp, generated)
    }

    /// K2's `Link` from the card at `from` to the card labelled `target`, at
    /// `feature`.
    fn link(&mut self, s: &Slots, writer: usize, from: At, feature: &str, target: &str) -> Sent {
        let source = label_at(from);
        let (slot, arc) = match feature {
            "blocker" => (s.blocker, "CardToCard"),
            "related" => (s.related, "CardToCard2"),
            other => panic!("the card has no reference `{other}`"),
        };
        let id = self.identity(target);
        let generated = json!({"AddReference": {arc: {
            "source": self.vertex_path(source),
            "target": self.vertex_path(target),
            "kind": null
        }}});
        self.send(
            writer,
            &format!("link {source}.{feature} -> {target}"),
            s.on_card(
                from,
                InstanceOp::field(slot, InstanceOp::Leaf(LeafOp::Link(id))),
            ),
            generated,
        )
    }

    /// The four links of N1, from `writer`: `x.blocker` and `x.related` to the
    /// target card, `x.related -> z`, and the target card's `related -> y`.
    fn links_to_and_from(&mut self, s: &Slots, writer: usize, at: At) -> Vec<Sent> {
        let target = label_at(at);
        vec![
            self.link(s, writer, At::Cards(0), "blocker", target),
            self.link(s, writer, At::Cards(0), "related", target),
            self.link(s, writer, At::Cards(0), "related", "z"),
            self.link(s, writer, at, "related", "y"),
        ]
    }
}

/// The base: the root, `x`, `y`, `z` at `Board.cards[0..3]` titled `x`, `y`,
/// `z`, and a frame at `holder` labelled `l` whose cards hold `h`
/// (`Frame.head`), `e` (`Frame.extra`) and `s` (`Frame.slots["k"]`), built on
/// replica 0 and delivered to all. Each card of the frame is labelled `H`,
/// `E`, `S`: on the generated side by the one vertex its first write added,
/// on the interpreted side by the identity it is served under.
fn base(s: &Slots, holder: Holder) -> Twin<NestGen> {
    let mut twin: Twin<NestGen> = Twin::new(&descriptor());
    twin.root(s);
    for (pos, label) in ["x", "y", "z"].into_iter().enumerate() {
        twin.new_card(s, pos, label);
        let ch = label.chars().next().expect("a one-letter label");
        let pair = twin.type_char(s, 0, At::Cards(pos), 0, ch);
        twin.deliver(1, &pair);
        twin.deliver(2, &pair);
    }
    let pair = twin.type_label(s, 0, holder, 0, 'l');
    twin.deliver(1, &pair);
    twin.deliver(2, &pair);
    for place in Place::ALL {
        let before = twin.vertex_set(0);
        let pair = twin.type_char(s, 0, At::Frame(holder, place), 0, place.letter());
        twin.deliver(1, &pair);
        twin.deliver(2, &pair);
        twin.label_new_vertex(0, &before, place.label());
        let doc = twin.identified(0);
        let frame = match holder {
            Holder::Pinned => &doc["pinned"],
            Holder::Keyed => &doc["frames"]["f"],
        };
        let card = match place {
            Place::Head => &frame["head"],
            Place::Extra => &frame["extra"],
            Place::Slot => &frame["slots"]["k"],
        };
        let id = card[ID]
            .as_str()
            .unwrap_or_else(|| panic!("the card at {place:?} carries no identity: {doc}"))
            .to_string();
        twin.label_identity(&id, place.label());
    }
    twin
}

/// The interpreted projection of one frame, and the links of its cards.
fn interp_frame(
    twin: &Twin<NestGen>,
    frame: &Value,
    links: &mut BTreeSet<(String, String, String)>,
) -> Result<Value, String> {
    let mut card = |value: &Value, label: &str| -> Result<Value, String> {
        if value.is_null() {
            return Ok(Value::Null);
        }
        twin.interp_links_of(label, value, links)?;
        Ok(json!(interp_text(value.get("title"))))
    };
    let head = card(frame.get("head").unwrap_or(&Value::Null), "H")?;
    let extra = card(frame.get("extra").unwrap_or(&Value::Null), "E")?;
    let mut slots = Map::new();
    for (key, value) in frame
        .get("slots")
        .and_then(Value::as_object)
        .cloned()
        .unwrap_or_default()
    {
        if key != "k" {
            return Err(format!(
                "the schedules write slot `k` alone, and `{key}` is served"
            ));
        }
        slots.insert(key, card(&value, "S")?);
    }
    Ok(json!({
        "label": interp_text(frame.get("label")),
        "head": head,
        "extra": extra,
        "slots": slots,
    }))
}

/// The interpreted projection of replica `at`: the titles of `Board.cards`,
/// the frame in `Board.pinned` and those of `Board.frames` (label and card
/// titles), and the links of every card.
fn project_interp(twin: &Twin<NestGen>, at: usize) -> Result<Projection, String> {
    let doc = twin.identified(at);
    let mut links = BTreeSet::new();
    let mut titles = Vec::new();
    for card in doc["cards"].as_array().cloned().unwrap_or_default() {
        let id = card[ID]
            .as_str()
            .ok_or_else(|| format!("a card carries no identity: {card}"))?;
        let label = twin
            .identities
            .get(id)
            .cloned()
            .ok_or_else(|| format!("interpreted card {id} carries no label"))?;
        titles.push(json!(interp_text(card.get("title"))));
        twin.interp_links_of(&label, &card, &mut links)?;
    }
    let pinned = match doc.get("pinned") {
        None | Some(Value::Null) => Value::Null,
        Some(frame) => interp_frame(twin, frame, &mut links)?,
    };
    let mut frames = Map::new();
    for (key, frame) in doc
        .get("frames")
        .and_then(Value::as_object)
        .cloned()
        .unwrap_or_default()
    {
        if key != "f" {
            return Err(format!(
                "the schedules write frame `f` alone, and `{key}` is served"
            ));
        }
        frames.insert(key, interp_frame(twin, &frame, &mut links)?);
    }
    Ok(Projection {
        containment: json!({"cards": titles, "pinned": pinned, "frames": frames}),
        links,
    })
}

/// The generated projection of one frame.
fn gen_frame(frame: &Value) -> Value {
    let title = |card: &Value| match card {
        Value::Null => Value::Null,
        card => json!(gen_text(&card["title"])),
    };
    let mut slots = Map::new();
    for (key, card) in frame["slots"].as_object().cloned().unwrap_or_default() {
        slots.insert(key, title(&card));
    }
    json!({
        "label": gen_text(&frame["label"]),
        "head": title(&frame["head"]),
        "extra": title(&frame["extra"]),
        "slots": slots,
    })
}

/// The generated projection of replica `at`, read off the typed read and its
/// graph.
fn project_gen(twin: &Twin<NestGen>, at: usize) -> Projection {
    let value = twin.gen_side.value(at);
    let titles: Vec<Value> = value["cards"]
        .as_array()
        .cloned()
        .unwrap_or_default()
        .iter()
        .map(|card| json!(gen_text(&card["title"])))
        .collect();
    let pinned = match &value["pinned"] {
        Value::Null => Value::Null,
        frame => gen_frame(frame),
    };
    let mut frames = Map::new();
    for (key, frame) in value["frames"].as_object().cloned().unwrap_or_default() {
        frames.insert(key, gen_frame(&frame));
    }
    Projection {
        containment: json!({"cards": titles, "pinned": pinned, "frames": frames}),
        links: twin
            .gen_links(at)
            .unwrap_or_else(|why| panic!("replica {at}, generated: {why}")),
    }
}

