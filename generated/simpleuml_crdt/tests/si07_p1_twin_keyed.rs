//! SI.07, claim P1 (parity), over a keyed source: `Board.slots` of
//! `si05keyed.ecore`, a keyed collection of `Card`s (`UWMapLog<String,
//! CardLog>` on the generated side), whose `Card` holds an optional text
//! `title` and an optional counter `rank`.
//!
//! The spec is `cea-cdrt-knowledge/spec/items/SI.07.md`; the claim is the one
//! `si07_p1_twin_board.rs` states, for a source at a key. On the generated
//! side a `Remove` of the key (or a `Clear`) is a `DeleteSubtree` over the
//! entry: it takes the card's vertex away, and the entry stays read while it
//! differs from a fresh card, which a title emptied by the removal does
//! (`Some("")` is not `None`), so the card stays served with title `""` while
//! no link from it is read.
//!
//! The generated runtime is Moirai's `moirai-interp/tests/fixtures/si05/
//! si05keyed.ecore`, generated by Arachne `2ef2a26` (`arachne generate -p
//! keyed_crdt`), its three source files copied unchanged into
//! `fixtures/si07/keyed/` and compiled here as this test's own modules; its
//! `metamodel.json` is byte for byte Moirai's `si05keyed.metamodel.json`
//! (sha256 `ce763243...`). The harness is `si07_twin/mod.rs`.
//!
//! ```bash
//! cd generated/simpleuml_crdt && nice -n 10 cargo test -j 2 --test si07_p1_twin_keyed
//! ```
