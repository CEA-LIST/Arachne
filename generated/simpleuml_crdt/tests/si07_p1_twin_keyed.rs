/// TK3, the other side: `b` removes `k`; `c`, concurrently, links `K.blocker`
/// to `y` and `K.related` to `z` and then raises `K.rank`. The rank is a
/// write the removal had not seen, so the card keeps its vertex and both
/// links are read on both paths, in every order.
#[test]
fn si07_p1_twin_tk3_a_write_concurrent_with_the_removal_keeps_the_links_read() {
    let s = Slots::new();
    let schedule = || {
        let mut twin = base(&s);
        let removal = twin.remove(&s, 1, "k");
        let blocker = twin.link(&s, 2, At::Key("k"), "K", "blocker", "y");
        let related = twin.link(&s, 2, At::Key("k"), "K", "related", "z");
        let rank = twin.rank_up(&s, 2, At::Key("k"));
        Run {
            twin,
            incoming: [
                vec![
                    vec![removal.clone()],
                    vec![blocker.clone(), related.clone(), rank.clone()],
                ],
                vec![vec![blocker, related, rank]],
                vec![vec![removal]],
            ],
        }
    };
    let runs = every_order(
        "TK3",
        Sides::Both,
        schedule,
        project,
        |agreed| {
            assert_eq!(
                agreed.containment,
                json!({"cards": base_titles(), "slots": {"k": {"title": "", "rank": 1}}}),
                "TK3: the entry holds the rank raised concurrently, its title emptied"
            );
            assert_eq!(
                agreed.links,
                links(&[("K", "blocker", "y"), ("K", "related", "z")]),
                "TK3: the links are read, the card being kept by a write the removal had not seen"
            );
        },
        None,
        |_| {},
    );
    assert_eq!(runs, 4, "a: 4 interleavings, b: 1 order, c: 1 order");
}
