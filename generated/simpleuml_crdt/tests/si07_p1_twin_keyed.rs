/// Where a card sits.
#[derive(Clone, Copy, Debug)]
enum At {
    Cards(usize),
    Key(&'static str),
}

struct Slots {
    board: ClassSlot,
    card: ClassSlot,
    cards: FeatureSlot,
    slots: FeatureSlot,
    title: FeatureSlot,
    rank: FeatureSlot,
    blocker: FeatureSlot,
    related: FeatureSlot,
}

impl Slots {
    fn new() -> Slots {
        let sem = table(&descriptor());
        let board = class_slot(&sem, "Board");
        let card = class_slot(&sem, "Card");
        Slots {
            board,
            card,
            cards: feature_slot(&sem, board, "cards"),
            slots: feature_slot(&sem, board, "slots"),
            title: feature_slot(&sem, card, "title"),
            rank: feature_slot(&sem, card, "rank"),
            blocker: feature_slot(&sem, card, "blocker"),
            related: feature_slot(&sem, card, "related"),
        }
    }

    fn on_board(&self, inner: InstanceOp) -> ModelOp {
        ModelOp::Instance(InstanceOp::variant(self.board, inner))
    }

    fn on_card(&self, at: At, inner: InstanceOp) -> ModelOp {
        let card = InstanceOp::variant(self.card, inner);
        self.on_board(match at {
            At::Cards(i) => InstanceOp::field(self.cards, InstanceOp::at(i, card)),
            At::Key(key) => {
                InstanceOp::field(self.slots, InstanceOp::entry(Scalar::text(key), card))
            }
        })
    }
}

fn gen_on_card(at: At, inner: Value) -> Value {
    match at {
        At::Cards(i) => json!({"Board": {"Cards": {"Update": {"pos": i, "op": inner}}}}),
        At::Key(key) => json!({"Board": {"Slots": {"Update": [key, inner]}}}),
    }
}

impl Twin<KeyedGen> {
    fn root(&mut self, s: &Slots) {
        self.broadcast(
            0,
            "the root",
            s.on_board(InstanceOp::New),
            json!({"Board": "New"}),
        );
    }

    /// A card created at `Board.cards[pos]` on replica 0, delivered, labelled.
    fn new_card(&mut self, s: &Slots, pos: usize, label: &str) {
        let before = self.vertex_set(0);
        self.broadcast(
            0,
            &format!("create {label}"),
            s.on_board(InstanceOp::field(
                s.cards,
                InstanceOp::insert(pos, InstanceOp::variant(s.card, InstanceOp::New)),
            )),
            json!({"Board": {"Cards": {"Insert": {"pos": pos, "op": "New"}}}}),
        );
        self.label_new_vertex(0, &before, label);
        let doc = self.identified(0);
        let id = doc["cards"][pos][ID]
            .as_str()
            .unwrap_or_else(|| panic!("no identity at Board.cards[{pos}] in {doc}"))
            .to_string();
        self.identities.insert(id, label.to_string());
    }

    /// One character typed at `pos` into the title of the card at `at`.
    fn type_char(
        &mut self,
        s: &Slots,
        writer: usize,
        at: At,
        pos: usize,
        ch: char,
    ) -> Pair<EventMessage<Si05keyed>> {
        self.send(
            writer,
            &format!("type {ch:?} into the title of {at:?}"),
            s.on_card(
                at,
                InstanceOp::field(
                    s.title,
                    InstanceOp::set(InstanceOp::Leaf(LeafOp::InsertChar { pos, ch })),
                ),
            ),
            gen_on_card(
                at,
                json!({"Title": {"Set": {"Insert": {"content": ch, "pos": pos}}}}),
            ),
        )
    }

    /// `rank` of the card at `at` up by one.
    fn rank_up(&mut self, s: &Slots, writer: usize, at: At) -> Pair<EventMessage<Si05keyed>> {
        self.send(
            writer,
            &format!("rank of {at:?} up by one"),
            s.on_card(
                at,
                InstanceOp::field(
                    s.rank,
                    InstanceOp::set(InstanceOp::Leaf(LeafOp::Inc(Scalar::Int(1)))),
                ),
            ),
            gen_on_card(at, json!({"Rank": {"Set": {"Inc": 1}}})),
        )
    }

    /// `Remove` of `key`.
    fn remove(&mut self, s: &Slots, writer: usize, key: &str) -> Pair<EventMessage<Si05keyed>> {
        self.send(
            writer,
            &format!("remove key {key}"),
            s.on_board(InstanceOp::field(
                s.slots,
                InstanceOp::remove(Scalar::text(key)),
            )),
            json!({"Board": {"Slots": {"Remove": key}}}),
        )
    }

    /// `Clear` of `Board.slots`.
    fn clear(&mut self, s: &Slots, writer: usize) -> Pair<EventMessage<Si05keyed>> {
        self.send(
            writer,
            "clear Board.slots",
            s.on_board(InstanceOp::field(s.slots, InstanceOp::clear())),
            json!({"Board": {"Slots": "Clear"}}),
        )
    }

    /// K2's `Link` from the card labelled `source` at `at` to the card
    /// labelled `target`, at `feature`.
    fn link(
        &mut self,
        s: &Slots,
        writer: usize,
        at: At,
        source: &str,
        feature: &str,
        target: &str,
    ) -> Pair<EventMessage<Si05keyed>> {
        let slot = if feature == "blocker" {
            s.blocker
        } else {
            s.related
        };
        let arc = if feature == "blocker" {
            "CardToCard"
        } else {
            "CardToCard2"
        };
        let id = self.identity(target);
        let generated = json!({"AddReference": {arc: {
            "source": self.vertex_path(source),
            "target": self.vertex_path(target),
            "kind": null
        }}});
        self.send(
            writer,
            &format!("link {source}.{feature} -> {target}"),
            s.on_card(
                at,
                InstanceOp::field(slot, InstanceOp::Leaf(LeafOp::Link(id))),
            ),
            generated,
        )
    }
}

/// The base: the root, `x`, `y`, `z` at `Board.cards[0..3]` titled `x`, `y`,
/// `z`, and a card at key `k` titled `p`, built on replica 0 and delivered
/// to all. The card at `k` is labelled `K` by its place.
fn base(s: &Slots) -> Twin<KeyedGen> {
    let mut twin: Twin<KeyedGen> = Twin::new(&descriptor());
    twin.root(s);
    for (pos, label) in ["x", "y", "z"].into_iter().enumerate() {
        twin.new_card(s, pos, label);
        let ch = label.chars().next().expect("a one-letter label");
        let pair = twin.type_char(s, 0, At::Cards(pos), 0, ch);
        twin.deliver(1, &pair);
        twin.deliver(2, &pair);
    }
    let before = twin.vertex_set(0);
    let pair = twin.type_char(s, 0, At::Key("k"), 0, 'p');
    twin.deliver(1, &pair);
    twin.deliver(2, &pair);
    twin.label_new_vertex(0, &before, "K");
    twin
}

/// Both paths' projection of replica `at`: the titles of `Board.cards`, every
/// key served with its card's title and rank, and the links of every card.
fn project(twin: &Twin<KeyedGen>, at: usize) -> (Projection, Projection) {
    let doc = twin.identified(at);
    let mut links = BTreeSet::new();
    let mut titles = Vec::new();
    for card in doc["cards"].as_array().cloned().unwrap_or_default() {
        let id = card[ID].as_str().expect("a card carries its identity");
        let label = twin
            .identities
            .get(id)
            .cloned()
            .unwrap_or_else(|| panic!("interpreted card {id} carries no label"));
        titles.push(json!(interp_text(card.get("title"))));
        twin.interp_links_of(&label, &card, &mut links)
            .unwrap_or_else(|why| panic!("replica {at}, interpreted: {why}"));
    }
    let mut slots = Map::new();
    for (key, card) in doc["slots"].as_object().cloned().unwrap_or_default() {
        assert_eq!(key, "k", "the schedules write key `k` alone");
        twin.interp_links_of("K", &card, &mut links)
            .unwrap_or_else(|why| panic!("replica {at}, interpreted: {why}"));
        slots.insert(
            key,
            json!({"title": interp_text(card.get("title")), "rank": card.get("rank").cloned().unwrap_or(Value::Null)}),
        );
    }
    let interp = Projection {
        containment: json!({"cards": titles, "slots": slots}),
        links,
    };

    let value = twin.gen_side.value(at);
    let titles: Vec<Value> = value["cards"]
        .as_array()
        .cloned()
        .unwrap_or_default()
        .iter()
        .map(|card| json!(gen_text(&card["title"])))
        .collect();
    let mut slots = Map::new();
    for (key, card) in value["slots"].as_object().cloned().unwrap_or_default() {
        slots.insert(
            key,
            json!({"title": gen_text(&card["title"]), "rank": card["rank"].clone()}),
        );
    }
    let generated = Projection {
        containment: json!({"cards": titles, "slots": slots}),
        links: twin
            .gen_links(at)
            .unwrap_or_else(|why| panic!("replica {at}, generated: {why}")),
    };
    (interp, generated)
}

fn links(items: &[(&str, &str, &str)]) -> BTreeSet<(String, String, String)> {
    items
        .iter()
        .map(|(s, f, t)| (s.to_string(), f.to_string(), t.to_string()))
        .collect()
}

fn base_titles() -> Value {
    json!(["x", "y", "z"])
}

/// TK1, the links the removal had seen: `K` links `blocker -> y` and
/// `related -> y, z`, delivered to all; then `b` removes `k`, delivered to
/// all. The emptied title keeps the entry on both paths (`""`); no link is
/// read.
#[test]
fn si07_p1_twin_tk1_links_the_removal_had_seen_are_not_read_from_the_entry_a_text_keeps() {
    let s = Slots::new();
    let mut twin = base(&s);
    for (feature, target) in [("blocker", "y"), ("related", "y"), ("related", "z")] {
        let pair = twin.link(&s, 0, At::Key("k"), "K", feature, target);
        twin.deliver(1, &pair);
        twin.deliver(2, &pair);
    }
    let held = compare(&twin, &project, "TK1, before the removal");
    assert_eq!(
        held.links,
        links(&[
            ("K", "blocker", "y"),
            ("K", "related", "y"),
            ("K", "related", "z")
        ]),
        "TK1 premise: both paths read the three links before the removal"
    );
    let remove = twin.remove(&s, 1, "k");
    twin.deliver(0, &remove);
    twin.deliver(2, &remove);
    let after = compare(&twin, &project, "TK1, after the removal");
    assert_eq!(
        after.containment,
        json!({"cards": base_titles(), "slots": {"k": {"title": "", "rank": null}}}),
        "TK1: the emptied title keeps the entry on both paths"
    );
    assert_eq!(
        after.links,
        links(&[]),
        "TK1: no link the removal had seen is read"
    );
}

/// TK2, the gap of SI.05's ruling R3.2 at a key. `b` removes `k` (or clears
/// the collection); `c`, concurrently, links `K.blocker` to `y` and
/// `K.related` to `z`. No write concurrent with the removal reaches the
/// card, so neither link is read while the emptied title keeps the entry
/// served. Then `a` raises `K.rank`, delivered to all: the write adds the
/// card's vertex again and both links are read again.
fn tk2(clear: bool, sides: Sides) {
    let s = Slots::new();
    let schedule = || {
        let mut twin = base(&s);
        let removal = if clear {
            twin.clear(&s, 1)
        } else {
            twin.remove(&s, 1, "k")
        };
        let blocker = twin.link(&s, 2, At::Key("k"), "K", "blocker", "y");
        let related = twin.link(&s, 2, At::Key("k"), "K", "related", "z");
        Run {
            twin,
            incoming: [
                vec![
                    vec![removal.clone()],
                    vec![blocker.clone(), related.clone()],
                ],
                vec![vec![blocker, related]],
                vec![vec![removal]],
            ],
        }
    };
    let revive = |twin: &mut Twin<KeyedGen>| {
        let s = Slots::new();
        let pair = twin.rank_up(&s, 0, At::Key("k"));
        twin.deliver(1, &pair);
        twin.deliver(2, &pair);
        "a raises the rank of the card at k"
    };
    let label = if clear { "TK2 (Clear)" } else { "TK2 (Remove)" };
    let runs = every_order(
        label,
        sides,
        schedule,
        project,
        |agreed| {
            assert_eq!(
                agreed.containment,
                json!({"cards": base_titles(), "slots": {"k": {"title": "", "rank": null}}}),
                "{label}: the emptied title keeps the entry"
            );
            assert_eq!(
                agreed.links,
                links(&[]),
                "{label}: no link from the card is read while no write keeps it"
            );
        },
        Some(&revive),
        |agreed| {
            assert_eq!(
                agreed.containment,
                json!({"cards": base_titles(), "slots": {"k": {"title": "", "rank": 1}}}),
                "{label}, revived: the card holds rank 1"
            );
            assert_eq!(
                agreed.links,
                links(&[("K", "blocker", "y"), ("K", "related", "z")]),
                "{label}, revived: the links no removal had seen are read again"
            );
        },
    );
    assert_eq!(runs, 3, "a: 3 interleavings, b: 1 order, c: 1 order");
}

#[test]
fn si07_p1_twin_tk2_links_concurrent_with_a_key_removal_follow_the_cards_vertex() {
    tk2(false, Sides::Both);
}

