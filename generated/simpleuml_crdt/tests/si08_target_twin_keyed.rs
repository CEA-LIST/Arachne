/// Where a card sits.
#[derive(Clone, Copy, Debug)]
enum At {
    Cards(usize),
    Key(&'static str),
}

struct Slots {
    board: ClassSlot,
    card: ClassSlot,
    cards: FeatureSlot,
    slots: FeatureSlot,
    title: FeatureSlot,
    rank: FeatureSlot,
    blocker: FeatureSlot,
    related: FeatureSlot,
}

impl Slots {
    fn new() -> Slots {
        let sem = table(&descriptor());
        let board = class_slot(&sem, "Board");
        let card = class_slot(&sem, "Card");
        Slots {
            board,
            card,
            cards: feature_slot(&sem, board, "cards"),
            slots: feature_slot(&sem, board, "slots"),
            title: feature_slot(&sem, card, "title"),
            rank: feature_slot(&sem, card, "rank"),
            blocker: feature_slot(&sem, card, "blocker"),
            related: feature_slot(&sem, card, "related"),
        }
    }

    fn on_board(&self, inner: InstanceOp) -> ModelOp {
        ModelOp::Instance(InstanceOp::variant(self.board, inner))
    }

    fn on_card(&self, at: At, inner: InstanceOp) -> ModelOp {
        let card = InstanceOp::variant(self.card, inner);
        self.on_board(match at {
            At::Cards(i) => InstanceOp::field(self.cards, InstanceOp::at(i, card)),
            At::Key(key) => {
                InstanceOp::field(self.slots, InstanceOp::entry(Scalar::text(key), card))
            }
        })
    }
}

fn gen_on_card(at: At, inner: Value) -> Value {
    match at {
        At::Cards(i) => json!({"Board": {"Cards": {"Update": {"pos": i, "op": inner}}}}),
        At::Key(key) => json!({"Board": {"Slots": {"Update": [key, inner]}}}),
    }
}

/// The label of the card at a place, for the source of a link.
fn label_at(at: At) -> &'static str {
    match at {
        At::Cards(0) => "x",
        At::Cards(1) => "y",
        At::Cards(2) => "z",
        At::Key("k") => "K",
        other => panic!("no card is labelled at {other:?}"),
    }
}

impl Twin<KeyedGen> {
    fn root(&mut self, s: &Slots) {
        self.broadcast(
            0,
            "the root",
            s.on_board(InstanceOp::New),
            json!({"Board": "New"}),
        );
    }

    /// A card created at `Board.cards[pos]` on replica 0, delivered, labelled.
    fn new_card(&mut self, s: &Slots, pos: usize, label: &str) {
        let before = self.vertex_set(0);
        self.broadcast(
            0,
            &format!("create {label}"),
            s.on_board(InstanceOp::field(
                s.cards,
                InstanceOp::insert(pos, InstanceOp::variant(s.card, InstanceOp::New)),
            )),
            json!({"Board": {"Cards": {"Insert": {"pos": pos, "op": "New"}}}}),
        );
        self.label_new_vertex(0, &before, label);
        let doc = self.identified(0);
        let id = doc["cards"][pos][ID]
            .as_str()
            .unwrap_or_else(|| panic!("no identity at Board.cards[{pos}] in {doc}"))
            .to_string();
        self.label_identity(&id, label);
    }

    /// One character typed at `pos` into the title of the card at `at`.
    fn type_char(
        &mut self,
        s: &Slots,
        writer: usize,
        at: At,
        pos: usize,
        ch: char,
    ) -> Pair<EventMessage<Si05keyed>> {
        self.send(
            writer,
            &format!("type {ch:?} into the title of {at:?}"),
            s.on_card(
                at,
                InstanceOp::field(
                    s.title,
                    InstanceOp::set(InstanceOp::Leaf(LeafOp::InsertChar { pos, ch })),
                ),
            ),
            gen_on_card(
                at,
                json!({"Title": {"Set": {"Insert": {"content": ch, "pos": pos}}}}),
            ),
        )
    }

    /// `rank` of the card at `at` up by one.
    fn rank_up(&mut self, s: &Slots, writer: usize, at: At) -> Pair<EventMessage<Si05keyed>> {
        self.send(
            writer,
            &format!("rank of {at:?} up by one"),
            s.on_card(
                at,
                InstanceOp::field(
                    s.rank,
                    InstanceOp::set(InstanceOp::Leaf(LeafOp::Inc(Scalar::Int(1)))),
                ),
            ),
            gen_on_card(at, json!({"Rank": {"Set": {"Inc": 1}}})),
        )
    }

    /// `Remove` of `k`, or `Clear` of `Board.slots`.
    fn removal(&mut self, s: &Slots, writer: usize, clear: bool) -> Pair<EventMessage<Si05keyed>> {
        if clear {
            self.send(
                writer,
                "clear Board.slots",
                s.on_board(InstanceOp::field(s.slots, InstanceOp::clear())),
                json!({"Board": {"Slots": "Clear"}}),
            )
        } else {
            self.send(
                writer,
                "remove key k",
                s.on_board(InstanceOp::field(
                    s.slots,
                    InstanceOp::remove(Scalar::text("k")),
                )),
                json!({"Board": {"Slots": {"Remove": "k"}}}),
            )
        }
    }

    /// K2's `Link` from the card at `from` to the card labelled `target`, at
    /// `feature`.
    fn link(
        &mut self,
        s: &Slots,
        writer: usize,
        from: At,
        feature: &str,
        target: &str,
    ) -> Pair<EventMessage<Si05keyed>> {
        let source = label_at(from);
        let slot = if feature == "blocker" {
            s.blocker
        } else {
            s.related
        };
        let arc = if feature == "blocker" {
            "CardToCard"
        } else {
            "CardToCard2"
        };
        let id = self.identity(target);
        let generated = json!({"AddReference": {arc: {
            "source": self.vertex_path(source),
            "target": self.vertex_path(target),
            "kind": null
        }}});
        self.send(
            writer,
            &format!("link {source}.{feature} -> {target}"),
            s.on_card(
                from,
                InstanceOp::field(slot, InstanceOp::Leaf(LeafOp::Link(id))),
            ),
            generated,
        )
    }
}

/// The base: the root, `x`, `y`, `z` at `Board.cards[0..3]` titled `x`, `y`,
/// `z`, and a card at key `k` titled `p`, built on replica 0 and delivered to
/// all. The card at `k` is labelled `K`: its vertex by its place, and the
/// identity it is served under.
fn base(s: &Slots) -> Twin<KeyedGen> {
    let mut twin: Twin<KeyedGen> = Twin::new(&descriptor());
    twin.root(s);
    for (pos, label) in ["x", "y", "z"].into_iter().enumerate() {
        twin.new_card(s, pos, label);
        let ch = label.chars().next().expect("a one-letter label");
        let pair = twin.type_char(s, 0, At::Cards(pos), 0, ch);
        twin.deliver(1, &pair);
        twin.deliver(2, &pair);
    }
    let before = twin.vertex_set(0);
    let pair = twin.type_char(s, 0, At::Key("k"), 0, 'p');
    twin.deliver(1, &pair);
    twin.deliver(2, &pair);
    twin.label_new_vertex(0, &before, "K");
    let doc = twin.identified(0);
    let id = doc["slots"]["k"][ID]
        .as_str()
        .unwrap_or_else(|| panic!("the card at k carries no identity: {doc}"))
        .to_string();
    twin.label_identity(&id, "K");
    twin
}

/// The interpreted projection of replica `at`: the titles of `Board.cards`,
/// every key served with its card's title and rank, and the links of every
/// card.
fn project_interp(twin: &Twin<KeyedGen>, at: usize) -> Result<Projection, String> {
    let doc = twin.identified(at);
    let mut links = BTreeSet::new();
    let mut titles = Vec::new();
    for card in doc["cards"].as_array().cloned().unwrap_or_default() {
        let id = card[ID]
            .as_str()
            .ok_or_else(|| format!("a card carries no identity: {card}"))?;
        let label = twin
            .identities
            .get(id)
            .cloned()
            .ok_or_else(|| format!("interpreted card {id} carries no label"))?;
        titles.push(json!(interp_text(card.get("title"))));
        twin.interp_links_of(&label, &card, &mut links)?;
    }
    let mut slots = Map::new();
    for (key, card) in doc["slots"].as_object().cloned().unwrap_or_default() {
        if key != "k" {
            return Err(format!(
                "the schedules write key `k` alone, and `{key}` is served"
            ));
        }
        twin.interp_links_of("K", &card, &mut links)?;
        slots.insert(
            key,
            json!({"title": interp_text(card.get("title")), "rank": card.get("rank").cloned().unwrap_or(Value::Null)}),
        );
    }
    Ok(Projection {
        containment: json!({"cards": titles, "slots": slots}),
        links,
    })
}

/// The generated projection of replica `at`.
fn project_gen(twin: &Twin<KeyedGen>, at: usize) -> Projection {
    let value = twin.gen_side.value(at);
    let titles: Vec<Value> = value["cards"]
        .as_array()
        .cloned()
        .unwrap_or_default()
        .iter()
        .map(|card| json!(gen_text(&card["title"])))
        .collect();
    let mut slots = Map::new();
    for (key, card) in value["slots"].as_object().cloned().unwrap_or_default() {
        slots.insert(
            key,
            json!({"title": gen_text(&card["title"]), "rank": card["rank"].clone()}),
        );
    }
    Projection {
        containment: json!({"cards": titles, "slots": slots}),
        links: twin
            .gen_links(at)
            .unwrap_or_else(|why| panic!("replica {at}, generated: {why}")),
    }
}

const PROJECT: Projector<'static, KeyedGen> = Projector {
    interp: &project_interp,
    generated: &project_gen,
};

fn containment(title: &str, rank: Value) -> Value {
    json!({"cards": ["x", "y", "z"], "slots": {"k": {"title": title, "rank": rank}}})
}

fn removal_name(clear: bool) -> &'static str {
    if clear { "Clear" } else { "Remove" }
}

/// TKT1, the links to the card at `k` that the removal had seen: `a` links
/// `x.blocker -> K` and `y.related -> K`, delivered to all; then `b` removes
/// `k` (or clears `Board.slots`) while `c`, concurrently, ranks the card up.
/// The rank adds the card's vertex again; the arcs the removal had seen stay
/// redundant, so no link is read, in every order, for both removals.
#[test]
fn si08_target_twin_tkt1_links_to_a_keyed_entry_the_removal_had_seen_stay_hidden() {
    let s = Slots::new();
    for clear in [false, true] {
        let label = format!("TKT1 ({})", removal_name(clear));
        let schedule = || {
            let mut twin = base(&s);
            for (from, feature) in [(At::Cards(0), "blocker"), (At::Cards(1), "related")] {
                let pair = twin.link(&s, 0, from, feature, "K");
                twin.deliver(1, &pair);
                twin.deliver(2, &pair);
            }
            let removal = twin.removal(&s, 1, clear);
            let rank = twin.rank_up(&s, 2, At::Key("k"));
            Run {
                twin,
                incoming: [
                    vec![vec![removal.clone()], vec![rank.clone()]],
                    vec![vec![rank]],
                    vec![vec![removal]],
                ],
            }
        };
        let runs = every_order(
            &label,
            Sides::Both,
            schedule,
            &PROJECT,
            |agreed| {
                assert_eq!(agreed.containment, containment("", json!(1)));
                assert_eq!(
                    agreed.links,
                    links(&[]),
                    "{label}: no link the removal had seen is read, although c's rank keeps the entry"
                );
            },
            None,
            Sides::Both,
            |_, _| {},
        );
        assert_eq!(runs, 2, "{label}: a: 2 interleavings, b: 1, c: 1");
    }
}

/// TKT2, the gap at a key: `b` removes `k` (or clears `Board.slots`); `c`,
/// concurrently, links `x.blocker -> K`, `x.related -> K` and
/// `x.related -> z`. No write the removal had not seen reaches the card, so
/// the generated graph reads only `x.related -> z` while the emptied title
/// keeps the entry. Under [`Sides::GeneratedOnly`] (the rehearsal), `a` then
/// ranks the card up, delivered to all, and the generated graph reads both
/// arcs to the card's place again: the revival of ruling R1, kept out of the
/// comparison of paths, the interpreted read there printed and not asserted.
fn tkt2(clear: bool, sides: Sides) {
    let s = Slots::new();
    let label = format!("TKT2 ({})", removal_name(clear));
    let schedule = || {
        let mut twin = base(&s);
        let removal = twin.removal(&s, 1, clear);
        let from_c = vec![
            twin.link(&s, 2, At::Cards(0), "blocker", "K"),
            twin.link(&s, 2, At::Cards(0), "related", "K"),
            twin.link(&s, 2, At::Cards(0), "related", "z"),
        ];
        Run {
            twin,
            incoming: [
                vec![vec![removal.clone()], from_c.clone()],
                vec![from_c],
                vec![vec![removal]],
            ],
        }
    };
    let revive = |twin: &mut Twin<KeyedGen>| {
        let s = Slots::new();
        let pair = twin.rank_up(&s, 0, At::Key("k"));
        twin.deliver(1, &pair);
        twin.deliver(2, &pair);
        "a ranks the card at k up (the revival of ruling R1)"
    };
    let after: Option<&dyn Fn(&mut Twin<KeyedGen>) -> &'static str> = match sides {
        Sides::Both => None,
        Sides::GeneratedOnly => Some(&revive),
    };
    let runs = every_order(
        &label,
        sides,
        schedule,
        &PROJECT,
        |agreed| {
            assert_eq!(
                agreed.containment,
                containment("", Value::Null),
                "{label}: the emptied title keeps the entry"
            );
            assert_eq!(
                agreed.links,
                links(&[("x", "related", "z")]),
                "{label}: no link to the card at k is read while no write the removal had not seen reaches it"
            );
        },
        after,
        Sides::GeneratedOnly,
        |twin, agreed| {
            assert_eq!(
                agreed.containment,
                containment("", json!(1)),
                "{label} rehearsal, revived: the card holds rank 1"
            );
            assert_eq!(
                agreed.links,
                links(&[
                    ("x", "blocker", "K"),
                    ("x", "related", "K"),
                    ("x", "related", "z")
                ]),
                "{label} rehearsal, revived: the generated graph reads the arcs to the card's place again"
            );
            let interp: Vec<String> = (0..3)
                .map(|at| match project_interp(twin, at) {
                    Ok(projection) => format!("{:?}", projection.links),
                    Err(why) => format!("unlabelled: {why}"),
                })
                .collect();
            println!(
                "SI08 OB2 observation, {label} (not asserted): after the revival the generated runtime \
                 reads {:?}; the interpreted path reads, per replica, {interp:?}; the card at k now \
                 serves {}",
                agreed.links,
                twin.identified(0)["slots"]["k"][ID]
            );
        },
    );
    assert_eq!(runs, 4, "{label}: a: 4 interleavings, b: 1, c: 1");
}

#[test]
fn si08_target_twin_tkt2_links_concurrent_with_a_key_removal_follow_the_entrys_vertex() {
    tkt2(false, Sides::Both);
}

#[test]
fn si08_target_twin_tkt2_links_concurrent_with_a_clear_follow_the_entrys_vertex() {
    tkt2(true, Sides::Both);
}

/// The harness's rehearsal of TKT2, both removals: the generated runtime
/// alone, held to the hand-computed answers in every order and after the
/// revival. Green before any implementation.
#[test]
fn si08_target_twin_rehearsal_tkt2_the_generated_runtime_reads_the_hand_computed_links() {
    tkt2(false, Sides::GeneratedOnly);
    tkt2(true, Sides::GeneratedOnly);
}

/// TKT4, the other side at a key: `b` removes `k` (or clears `Board.slots`);
/// `c`, concurrently, links `x.blocker -> K` and `x.related -> K`; `a`,
/// concurrently, ranks the card up. The rank's `AddVertex` is concurrent with
/// the `DeleteSubtree`, so both links are read on both paths, in every
/// order, for both removals.
#[test]
fn si08_target_twin_tkt4_a_write_the_removal_had_not_seen_keeps_the_links_to_the_entry_read() {
    let s = Slots::new();
    for clear in [false, true] {
        let label = format!("TKT4 ({})", removal_name(clear));
        let schedule = || {
            let mut twin = base(&s);
            let rank = twin.rank_up(&s, 0, At::Key("k"));
            let removal = twin.removal(&s, 1, clear);
            let from_c = vec![
                twin.link(&s, 2, At::Cards(0), "blocker", "K"),
                twin.link(&s, 2, At::Cards(0), "related", "K"),
            ];
            Run {
                twin,
                incoming: [
                    vec![vec![removal.clone()], from_c.clone()],
                    vec![vec![rank.clone()], from_c],
                    vec![vec![rank], vec![removal]],
                ],
            }
        };
        let runs = every_order(
            &label,
            Sides::Both,
            schedule,
            &PROJECT,
            |agreed| {
                assert_eq!(agreed.containment, containment("", json!(1)));
                assert_eq!(
                    agreed.links,
                    links(&[("x", "blocker", "K"), ("x", "related", "K")]),
                    "{label}: both links to the card at k are read, a write the removal had not seen keeping it"
                );
            },
            None,
            Sides::Both,
            |_, _| {},
        );
        assert_eq!(
            runs, 18,
            "{label}: a: 3 interleavings, b: 3 interleavings, c: 2 interleavings"
        );
    }
}
