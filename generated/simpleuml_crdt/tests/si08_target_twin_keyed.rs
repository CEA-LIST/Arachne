//! SI.08, the target side of SI.07's P1, over a keyed target: the card at key
//! `k` of `Board.slots` of `si05keyed.ecore`, a keyed collection of `Card`s
//! (`UWMapLog<String, CardLog>` on the generated side), whose `Card` holds an
//! optional text `title` and an optional counter `rank`.
//!
//! The spec is `cea-cdrt-knowledge/spec/items/SI.08.md`; the claim is the one
//! `si08_target_twin_board.rs` states, for a target at a key. On the
//! generated side a `Remove` of the key (or a `Clear`) is a `DeleteSubtree`
//! over the entry: it takes the card's vertex away, and the entry stays read
//! while it differs from a fresh card, which a title emptied by the removal
//! does (`Some("")` is not `None`), so the card stays served with title `""`
//! while no arc to it is read.
//!
//! The generated runtime is Moirai's `moirai-interp/tests/fixtures/si05/
//! si05keyed.ecore`, generated by Arachne `2ef2a26` (`arachne generate -p
//! keyed_crdt`), the three source files SI.07 copied into
//! `fixtures/si07/keyed/`, compiled here as this test's own modules; its
//! `metamodel.json` is byte for byte Moirai's `si05keyed.metamodel.json`. The
//! harness is `si08_twin/mod.rs`.
//!
//! ```bash
//! cd generated/simpleuml_crdt && nice -n 10 cargo test -j 2 --test si08_target_twin_keyed
//! ```
