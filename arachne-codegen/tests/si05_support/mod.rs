//! SI.05 (`cea-cdrt-knowledge/spec/items/SI.05.md`), section 3.1: the one transform every
//! descriptor comparison of this crate's tests applies to its expected side from SI.05 on.
//!
//! `arachne describe` names the new reference rule on every reference entry whose rule today is
//! `{"kind": "reference", "many", "target"}` and that declares no `eOpposite`: its `merge`
//! becomes `{"kind": "identityReference", "many", "target"}` with the same `many` and `target`,
//! and nothing else of the descriptor moves (no key added or removed, `formatVersion` still 2,
//! `provenance` unchanged). A reference that declares an `eOpposite` keeps today's rule (Cam's
//! decision 3), and an `EObject`-typed one keeps `{"kind": "unsupported", ...}`.
//!
//! The checked-in descriptors (`examples/*.metamodel.json`, `generated/*/metamodel.json`) are
//! not regenerated by SI.05 (the spec's scoping decision S1): they are the descriptors of the
//! models created under them, which keep today's rule (claim R6, no migration). So a test that
//! held `describe(ecore)` to a checked-in file now holds it to that file moved by this rule.
#![allow(dead_code)]

use serde_json::{Value, json};

/// Move every in-scope reference entry of `descriptor` to the identity rule; answers how many
/// moved.
pub fn identity_rule(descriptor: &mut Value) -> usize {
    let mut moved = 0;
    if let Some(classes) = descriptor.get_mut("classes").and_then(Value::as_object_mut) {
        for body in classes.values_mut() {
            if let Some(entries) = body.get_mut("references").and_then(Value::as_array_mut) {
                for entry in entries {
                    let today = entry["merge"]["kind"] == json!("reference");
                    if today && entry.get("eOpposite").is_none() {
                        let many = entry["merge"]["many"].clone();
                        let target = entry["merge"]["target"].clone();
                        entry["merge"] =
                            json!({"kind": "identityReference", "many": many, "target": target});
                        moved += 1;
                    }
                }
            }
        }
    }
    moved
}

/// `descriptor` moved by [`identity_rule`], as a new value.
pub fn with_identity_rule(descriptor: &Value) -> Value {
    let mut out = descriptor.clone();
    identity_rule(&mut out);
    out
}

/// A descriptor rendered as the generator writes it: `{:#}` and a newline.
pub fn render(descriptor: &Value) -> String {
    format!("{descriptor:#}\n")
}

/// The inverse, for the tests that guard everything but the reference rule (AR.01, AR.02, AR.04,
/// ED.10, ED.16a): every `identityReference` read back as today's `reference`, with the same
/// `many` and `target`; answers how many. Before SI.05 no descriptor carries one, so this is the
/// identity and those tests run as they always did; after it, they hold that nothing but the
/// rule SI.05 names moved, and `si05_identity_reference_emitter.rs` holds the rule itself.
pub fn todays_rule(descriptor: &mut Value) -> usize {
    let mut moved = 0;
    if let Some(classes) = descriptor.get_mut("classes").and_then(Value::as_object_mut) {
        for body in classes.values_mut() {
            if let Some(entries) = body.get_mut("references").and_then(Value::as_array_mut) {
                for entry in entries {
                    if entry["merge"]["kind"] == json!("identityReference") {
                        let many = entry["merge"]["many"].clone();
                        let target = entry["merge"]["target"].clone();
                        entry["merge"] =
                            json!({"kind": "reference", "many": many, "target": target});
                        moved += 1;
                    }
                }
            }
        }
    }
    moved
}

/// `descriptor` read back by [`todays_rule`].
pub fn read_back(mut descriptor: Value) -> Value {
    todays_rule(&mut descriptor);
    descriptor
}

/// A rendered descriptor's bytes read back by [`todays_rule`] and rendered again; bytes that are
/// not a JSON descriptor come back as they went in.
pub fn read_back_bytes(bytes: Vec<u8>) -> Vec<u8> {
    let Ok(mut descriptor) = serde_json::from_slice::<Value>(&bytes) else {
        return bytes;
    };
    if todays_rule(&mut descriptor) > 0 {
        render(&descriptor).into_bytes()
    } else {
        bytes
    }
}
